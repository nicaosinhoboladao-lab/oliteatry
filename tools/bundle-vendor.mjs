#!/usr/bin/env node
/**
 * Regenerates the vendored renderer bundles under src/renderer/vendor/.
 *
 * The renderer is loaded as plain ES modules (no bundler at runtime), so we
 * bundle third-party libraries once at author time and commit the output —
 * the same pattern already used for vendor/three.module.js. Every bundle keeps
 * `three` external (bare import), which the import map resolves to the single
 * shared vendor/three.module.js so instanceof/Object3D identity never splits.
 *
 *   npm run vendor
 */
import { build } from 'esbuild';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(here, '..');
const OUT = path.join(ROOT, 'src', 'renderer', 'vendor');

const targets = [
  {
    outfile: path.join(OUT, 'addons.module.js'),
    banner: '/* auto-generated by tools/bundle-vendor.mjs — do not edit */',
    entry: `
      export { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
      export { FBXLoader } from 'three/addons/loaders/FBXLoader.js';
      export { OBJLoader } from 'three/addons/loaders/OBJLoader.js';
      export { MTLLoader } from 'three/addons/loaders/MTLLoader.js';
      export { STLLoader } from 'three/addons/loaders/STLLoader.js';
      export { PLYLoader } from 'three/addons/loaders/PLYLoader.js';
      export { ColladaLoader } from 'three/addons/loaders/ColladaLoader.js';
      export { TransformControls } from 'three/addons/controls/TransformControls.js';
      export { OrbitControls } from 'three/addons/controls/OrbitControls.js';
    `,
  },
  {
    outfile: path.join(OUT, 'three-vrm.module.js'),
    banner: '/* auto-generated by tools/bundle-vendor.mjs — do not edit */',
    entry: `
      export { VRM, VRMLoaderPlugin, VRMUtils, VRMExpressionPresetName, VRMHumanBoneName } from '@pixiv/three-vrm';
    `,
  },
];

await mkdir(OUT, { recursive: true });

// Keep only the bare `three` specifier external (so a single shared three.js
// instance is used — no split Object3D identity), but emit it as a relative
// path: the renderer is loaded as plain ES modules with no import map.
const externalThreeOnly = {
  name: 'external-three-only',
  setup(b) {
    b.onResolve({ filter: /^three$/ }, () => ({ path: './three.module.js', external: true }));
  },
};

for (const t of targets) {
  await build({
    stdin: {
      contents: t.entry,
      resolveDir: ROOT,
      sourcefile: t.outfile.endsWith('three-vrm.module.js') ? 'three-vrm-entry.js' : 'addons-entry.js',
      loader: 'js',
    },
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    plugins: [externalThreeOnly],
    banner: { js: t.banner },
    outfile: t.outfile,
    minify: false,
    logLevel: 'info',
  });
  // eslint-disable-next-line no-console
  console.log('bundled', path.relative(ROOT, t.outfile));
}
